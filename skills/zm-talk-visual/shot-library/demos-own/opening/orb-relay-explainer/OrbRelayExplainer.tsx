import React from 'react';
import {AbsoluteFill, useCurrentFrame} from 'remotion';
import {Grain} from '../../../kit/polish';
import {kf, EASE} from './orb-kit';
import {S1, S2S3, S4, S5, Panel, poseAt} from './scenes-a';
import {S6S7, S8, S9, S10} from './scenes-b';
import {S11, S12, S13S15, S16, S17} from './scenes-c';

export const ORB_RELAY_EXPLAINER_DURATION = 1201;

export const OrbRelayExplainer: React.FC = () => {
  const f = useCurrentFrame();
  const t = f / 30;
  let scene: React.ReactNode;
  if (f < 81) scene = <S1 t={t} />;
  else if (f < 177) {
    const op = kf(t, [[5.58, 0], [5.62, 0.08], [5.7, 0.15], [5.8, 0.5], [5.9, 1]]);
    const wash = kf(t, [[5.58, 1], [5.75, 0.7], [5.9, 0.1, EASE.out]]);
    scene = <S2S3 t={t} panel={t >= 5.58 ? <Panel t={t} pose={poseAt(t)} wash={wash} opacity={op} /> : null} />;
  } else if (f < 238) scene = <S4 t={t} />;
  else if (f < 283) scene = <S5 t={t} />;
  else if (f < 441) scene = <S6S7 t={t} />;
  else if (f < 506) scene = <S8 t={t} />;
  else if (f < 558) scene = <S9 t={t} />;
  else if (f < 617) scene = <S10 t={t} />;
  else if (f < 783) scene = <S11 t={t} />;
  else if (f < 833) scene = <S12 t={t} />;
  else if (f < 975) scene = <S13S15 t={t} />;
  else if (f < 1090) scene = <S16 t={t} />;
  else scene = <S17 t={t} />;
  return (
    <AbsoluteFill style={{background: '#000005'}}>
      {scene}
      <Grain opacity={0.07} blend="soft-light" step={2} />
    </AbsoluteFill>
  );
};
